(function (global) {
  "use strict";
  var THREE = global.THREE;
  if (!THREE) return;
  global.SCENE_FACTORIES = global.SCENE_FACTORIES || {};
  global.SCENE_FACTORIES.obed = function () {
    var scene = new THREE.Scene();
    scene.background = new THREE.Color(0x2a1e10);
    if (global.makeFog) global.makeFog(scene, 0x2a1e10, 0.002);
    scene.add(new THREE.AmbientLight(0xffffff, 0.35));
    var sun = new THREE.DirectionalLight(0xFFE8A0, 0.9);
    sun.position.set(0, 25, 20);
    scene.add(sun);
    var ground = new THREE.Mesh(new THREE.PlaneGeometry(80, 60), global.toonMat({ color: 0x6a5838 }));
    ground.rotation.x = -Math.PI / 2;
    ground.position.y = -10;
    scene.add(ground);
    var house = new THREE.Mesh(new THREE.BoxGeometry(14, 9, 10), global.toonMat({ color: 0xC8a878 }));
    house.position.set(-5, -5, -8);
    scene.add(house);
    var roof = new THREE.Mesh(new THREE.ConeGeometry(10, 4, 4), global.toonMat({ color: 0x5a3818 }));
    roof.position.set(-5, 1.5, -8);
    roof.rotation.y = Math.PI / 4;
    scene.add(roof);
    var cradle = new THREE.Mesh(new THREE.BoxGeometry(3, 1.5, 2), global.toonMat({ color: 0x7a5830 }));
    cradle.position.set(5, -8.5, 5);
    scene.add(cradle);
    var blanket = new THREE.Mesh(new THREE.BoxGeometry(2.8, 0.3, 1.8), global.toonMat({ color: 0xE8D8B8 }));
    blanket.position.set(5, -7.6, 5);
    scene.add(blanket);
    var tree = new THREE.Mesh(new THREE.SphereGeometry(5, 10, 8), global.toonMat({ color: 0x4a6830 }));
    tree.position.set(20, -2, -15);
    scene.add(tree);
    var trunk = new THREE.Mesh(new THREE.CylinderGeometry(0.5, 0.7, 10, 8), global.toonMat({ color: 0x4a3018 }));
    trunk.position.set(20, -5, -15);
    scene.add(trunk);
    return { scene: scene, cameraConfig: { distance: 45, height: 12 } };
  };
})(window);
