import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = process.env.STORY_TEST_URL || 'http://127.0.0.1:8123';
const browser = await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-swiftshader']});
try {
  const context = await browser.newContext({viewport:{width:1440,height:900},serviceWorkers:'block'});
  const page = await context.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base,{waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.querySelector('#cityScene').dataset.state==='ready');
  await page.waitForTimeout(1000);
  assert.equal(await page.locator('.city-caption').count(),0,'Landscape title overlay must be removed');
  assert.equal(await page.locator('.city-fog').count(),28,'Small cloud banks must populate the scroll route');
  assert.equal(await page.locator('.city-bird').count(),9,'The scene must include the flock');
  const birdStart=await page.locator('.city-bird').first().getAttribute('style');
  const groupSizes=await page.locator('.city-fog').evaluateAll(groups=>groups.map(group=>group.querySelectorAll('.cloud-puff').length));
  assert.ok(groupSizes.every(size=>size>=4&&size<=7),'Cloud groups must contain overlapping puffs of varied sizes');
  const cloudEdges=await page.evaluate(async()=>{
    const image=new Image();image.src='assets/city-of-david/mist.svg?v=soft-edges13';await image.decode();
    const canvas=document.createElement('canvas');canvas.width=1200;canvas.height=360;
    const ctx=canvas.getContext('2d');ctx.drawImage(image,0,0,1200,360);
    const data=ctx.getImageData(0,0,1200,360).data;let edgeAlpha=0,peakAlpha=0;
    for(let y=0;y<360;y++)for(let x=0;x<1200;x++){
      const alpha=data[(y*1200+x)*4+3];peakAlpha=Math.max(peakAlpha,alpha);
      if(x<4||x>=1196||y<4||y>=356)edgeAlpha=Math.max(edgeAlpha,alpha);
    }
    return {edgeAlpha,peakAlpha};
  });
  assert.equal(cloudEdges.edgeAlpha,0,'Fog texture must have fully transparent borders on all four sides');
  assert.ok(cloudEdges.peakAlpha>100,'Fog texture must remain visible in its interior');
  const rotation=()=>page.locator('.comic-cover').evaluate(node=>{
    const matrix=new DOMMatrix(getComputedStyle(node).transform);
    return Math.atan2(matrix.b,matrix.a)*180/Math.PI;
  });
  assert.ok(Math.abs(await rotation()+2)<.01,'Story cover must keep its two-degree rotation');
  await page.locator('.comic-cover').hover();
  assert.ok(Math.abs(await rotation()+2)<.01,'Hover must preserve the cover rotation');
  await page.locator('.comic-cover').evaluate(node=>node.classList.add('can-scroll-down','can-scroll-up'));
  assert.ok(Math.abs(await rotation()+2)<.01,'Scroll hint classes must preserve rotation');
  const scene=page.locator('#cityScene canvas');
  const capture=()=>scene.screenshot({style:'.comic-cover,.city-caption,.city-controls,.copyright-notice,.mouse-highlight {visibility:hidden!important}'});
  const before=await capture();
  await page.waitForTimeout(800);
  assert.ok(!before.equals(await capture()),'Cloud layers must drift while movement is enabled');
  assert.notEqual(await page.locator('.city-bird').first().getAttribute('style'),birdStart,'Birds must fly while the scene is playing');
  await page.mouse.move(1300,150);
  assert.equal(await page.locator('.mouse-highlight').evaluate(node=>node.style.getPropertyValue('--highlight-x')),'1300px','Highlight must follow the pointer');
  assert.equal(await page.locator('.comic-screen-overlay').evaluate(node=>getComputedStyle(node).pointerEvents),'none','Comic overlay must not block story links');
  await page.waitForTimeout(1300);
  assert.ok(!before.equals(await capture()),'Pointer movement must change the rendered viewpoint');
  const fogBefore=await page.locator('.city-fog--near').evaluate(node=>getComputedStyle(node).transform);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight),'Page must fit the viewport');
  assert.equal(await page.locator('.comic-list').evaluate(node=>getComputedStyle(node).overflowY),'auto','Story list must scroll inside the cover');
  await page.locator('.comic-list').evaluate(list=>list.scrollTop=list.scrollHeight);
  await page.waitForTimeout(1200);
  assert.equal(await page.evaluate(()=>scrollY),0,'Page must stay still while the menu scrolls');
  assert.ok(await page.locator('.comic-list').evaluate(list=>list.scrollTop>0),'Menu must scroll');
  const fogAfter=await page.locator('.city-fog--near').evaluate(node=>getComputedStyle(node).transform);
  assert.notEqual(fogBefore,fogAfter,'Foreground fog must shift with window scrolling');
  const fogRise=await page.locator('.city-fog--near').evaluate(node=>new DOMMatrix(getComputedStyle(node).transform).m42);
  assert.ok(fogRise < -450,'Near fog must rise visibly through at least half a desktop viewport');
  assert.ok(!before.equals(await capture()),'Scene must respond while scrolling down');
  assert.ok(Math.abs(await rotation()+2)<.01,'Window scrolling must preserve rotation');
  await page.locator('.comic-list').evaluate(list=>list.scrollTop=0);
  await page.waitForTimeout(800);
  assert.equal(await page.evaluate(()=>scrollY),0,'Window must scroll back up');
  await page.click('#cityMotion');
  assert.equal(await page.locator('#cityMotion').getAttribute('aria-pressed'),'true');
  await page.waitForTimeout(1800);
  const paused=await capture();
  const pausedBird=await page.locator('.city-bird').first().innerHTML()+await page.locator('.city-bird').first().getAttribute('style');
  await page.mouse.move(30,700);
  await page.waitForTimeout(500);
  assert.ok(paused.equals(await capture()),'Paused city and cloud layers must remain still');
  assert.equal(await page.locator('.city-bird').first().innerHTML()+await page.locator('.city-bird').first().getAttribute('style'),pausedBird,'Paused birds must stop flying and flapping');
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(500);
  const layout=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth,scene:document.querySelector('#cityScene').getBoundingClientRect().toJSON(),menu:document.querySelector('.comic-cover').getBoundingClientRect().toJSON()}));
  assert.ok(layout.width<=layout.viewport,'Mobile page must not overflow horizontally');
  assert.equal(layout.scene.top,0,'Mobile scene must start at the top of the page');
  assert.ok(layout.menu.left>=0 && layout.menu.right<=layout.viewport,'Mobile menu must fit');
  assert.ok(layout.menu.top>=80,'Mobile cover must leave room for the city heading');
  assert.ok(layout.menu.bottom<=844-65,'Mobile cover must leave room for bottom controls');
  assert.ok(layout.menu.height<844*.8,'Mobile cover must have a bounded height');
  assert.ok(await page.locator('.comic-list').evaluate(list=>list.scrollHeight>list.clientHeight),'Mobile story list must overflow inside its own scroll area');
  const links=await page.locator('.comic-list a').count();
  assert.equal(links,22,'All existing story links must remain');
  await page.locator('.comic-list a').last().scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>scrollY),0,'Mobile page must stay still');
  assert.ok(await page.locator('.comic-list').evaluate(list=>list.scrollTop>0),'Last story must be reachable by internal menu scrolling');
  assert.ok(Math.abs(await rotation()+2)<.01,'Mobile scrolling must preserve rotation');
  assert.ok(await page.locator('.comic-list a').last().isVisible());
  assert.deepEqual(errors,[],'Scene must not produce JavaScript errors');
  await context.close();
  const reduced=await browser.newContext({reducedMotion:'reduce',serviceWorkers:'block'});
  const rp=await reduced.newPage();await rp.goto(base,{waitUntil:'networkidle'});
  assert.equal(await rp.locator('#cityMotion').getAttribute('aria-pressed'),'true');
  assert.ok(await rp.locator('#cityViewpoint').isDisabled());
  const reducedRotation=await rp.locator('.comic-cover').evaluate(node=>{const m=new DOMMatrix(getComputedStyle(node).transform);return Math.atan2(m.b,m.a)*180/Math.PI;});
  assert.ok(Math.abs(reducedRotation+2)<.01,'Reduced motion must preserve rotation');
  await reduced.close();
  const fallback=await browser.newContext({serviceWorkers:'block'});
  const fp=await fallback.newPage();
  await fp.addInitScript(()=>{HTMLCanvasElement.prototype.getContext=function(){return null;};});
  await fp.goto(base,{waitUntil:'networkidle'});
  assert.equal(await fp.locator('#cityScene').getAttribute('data-state'),'fallback');
  assert.ok(await fp.locator('#cityMotion').isHidden());
  assert.equal(await fp.locator('.comic-list a').count(),22);
  const manifest=JSON.parse(fs.readFileSync(path.join(root,'precache-manifest.json'),'utf8'));
  for(const asset of ['scene.js','scene.css','fallback.svg','mist.svg','cloud-puff.svg']) assert.ok(manifest.urls.includes(`assets/city-of-david/${asset}`),`${asset} must be precached`);
  console.log('Passed: 3D rendering, comic overlay, pointer highlight, cloud drift, flying birds, scrolling fog, pointer and menu-scroll parallax, persistent rotation, pause, mobile layout, reduced motion, static fallback, story links, and offline asset manifest.');
} finally { await browser.close(); }
