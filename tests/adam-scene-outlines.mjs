import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({console});
context.window=context;
vm.runInContext(fs.readFileSync('Adam/vendor/three.r128.min.js','utf8'),context);
context.document={createElement:()=>({}),head:{appendChild:script=>script.onload()}};
vm.runInContext(fs.readFileSync('Adam/js/adam-scenes-helpers.js','utf8'),context);
const {THREE}=context;
const group=new THREE.Group();
const parent=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshPhongMaterial({color:0xffaa00}));
const nested=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshPhongMaterial());
parent.add(nested);group.add(parent);
const count=()=>{let n=0;group.traverse(()=>n++);return n;};
context.toonizeGroup(group);
assert.equal(count(),5);
context.toonizeGroup(group);
assert.equal(count(),5,'Repeated conversion must not add duplicate outlines');
assert.equal(parent.children.filter(c=>c.userData.isToonOutline).length,1);
context.initScene1=target=>target.add(new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshPhongMaterial()));
context.loadJSScene('scene.js',group);
assert.equal(count(),7,'Loading a scene must add only one outline per source mesh');
const splineRoot=new THREE.Group();
splineRoot.add(new THREE.Group());
splineRoot.children[0].add(new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshPhongMaterial()));
THREE.GLTFLoader=class{load(url,loaded){loaded({scene:splineRoot});}};
const spline=context.loadSplineScene('scene.glb');
assert.equal(spline.children[0],splineRoot);
assert.equal(splineRoot.children[0].children.length,1,'Preserve imported scene hierarchy');
assert.equal(splineRoot.children[0].children[0].children.length,1);
console.log('Passed: nested meshes, repeat conversion, JS scene loading and GLTF hierarchy without recursive outlines.');
